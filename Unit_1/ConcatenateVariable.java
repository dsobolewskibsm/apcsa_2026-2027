public class ConcatenateVariable {
    public static void main(String[] args) {
        int justANumber = 7;
        int sonBirthdayDay = 18;
        int sonBirthdayYear = 2020;

        System.out.println(justANumber);
        System.out.println("My son was born on September " + sonBirthdayDay + ", " + sonBirthdayYear +".");
    }
}
